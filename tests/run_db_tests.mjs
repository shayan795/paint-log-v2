#!/usr/bin/env node
/**
 * データベースのテストについて（実行方法の案内）
 *
 *   使い方:  node tests/run_db_tests.mjs
 *
 * ★このスクリプトは、以前は開発用DBへ接続してテストを実行しようとしていた。
 *   しかし **匿名キーでは構造的に実行できない** ことが分かったため、案内役に変更した。
 *
 *   理由: DBテストは「その人としてログインした状態」を作らないと権限の検証にならず、
 *         そのために PostgreSQL の `set role` を使っている。
 *         匿名キー(anon)にはロールを切り替える権限が無いので、
 *         必ず「permission denied for table recipes」で止まる。
 *         鍵を変えれば動くという話ではなく、経路として無理。
 *
 *   以前はこの失敗が分かりにくいエラーで終わっていたため、
 *   「テストが通っていない」ことに気づけない状態だった（外部監査の指摘#12）。
 *   黙って失敗するより、実行方法を案内する方が役に立つ。
 */

const G = "\x1b[32m", Y = "\x1b[33m", B = "\x1b[1m", X = "\x1b[0m";

console.log(`
${B}データベースのテスト（605本）の実行方法${X}

このスクリプトからは実行できません（理由はファイル冒頭のコメント）。
次のどちらかで実行してください。

${B}① Claude（AI）に頼む${X}   ← ふだんはこちら
   「データベースのテストを流して」と言えば実行し、結果を日本語で報告します。
   Supabaseの管理接続を使うため、上記の制約を受けません。

${B}② 自分で実行する${X}
   Supabase の ${B}開発用プロジェクト（plamo-paint-dev）${X} を開き、
   SQL Editor に次を貼って Run:

       select * from public.test_report();

   区分ごとに「実行／合格／不合格」が表で出ます。
   ${B}★合計${X} の行だけ見れば全体の合否が分かります。

${G}最後に確認した結果: 605本すべて合格（2026-08-01）${X}

${Y}⚠️ 必ず開発用プロジェクトで実行してください。${X}
   本番には tests スキーマを入れていないので、間違えても動きません。

${Y}⚠️ 既知の課題:${X} テストの一部が、リポジトリではなく開発用DBの中だけに存在します。
   空のDBから再現する手順は tests/README.md に書いてありますが、
   DB内で直接直した分は追いついていない場合があります。
`);

// ★このスクリプト自体は「案内」なので常に成功で終わる。
//   失敗にすると、他のテストとまとめて流したときに毎回赤くなって邪魔になる。
process.exit(0);
