-- (1) BAN隔離がランキングを素通りしていた
--     popular_paints / rising_paints / popular_methods は security definer のため
--     「所有者の権限」で動き、RLSポリシーが適用されない。
--     025でレシピ本体は隠れるようにしたのに、トップの「人気の塗料」は別経路で作られており、
--     停止した人のカバー画像が一番目立つ場所に出続けていた。
--     権利侵害の画像を投稿した人を止めても被害が続く＝隔離の目的が達成できていなかった。
--     → 3関数の結合条件に停止判定を書き足した。
--
-- (2) 022の列権限剥奪が空振りしていた
--     Postgresは「テーブル全体のSELECT権限」がある限り、列単位のrevokeを無視する。
--     022は列単位でしか外しておらず、実際には何も剥奪できていなかった。
--     本番はたまたま別作業でテーブル権限が外れていて助かっていたが、
--     migrations から作り直すと穴が開く（復旧したら脆弱に戻る）。
--     → 007がanonに対して行っている手順と同じく、テーブル権限を外してから
--       公開してよい列だけを付け直す。
--
-- (3) 「誰が停止中か」を匿名がRPCで直接聞けた
--     025で作った owner_is_banned() が public にあり、
--     PostgRESTはpublicの関数を全部APIとして公開するため、
--     /rest/v1/rpc/owner_is_banned にIDを渡せば1件ずつ確認できた。
--     022でbanned_at列を隠した意味が消えていた。
--
--     ★ここで一度やってはいけない対処をした（実際に本番を約2分停止させた）:
--       revoke execute ... from anon, authenticated
--       → この関数はRLSポリシーの中で呼ばれるため、問い合わせている本人に実行権が無いと
--         ポリシーの評価自体が失敗し、レシピが1件も読めなくなる（本番が503になった）。
--       教訓: **RLSで使う関数の実行権は、利用者ロールから絶対に外してはいけない。**
--
--     → 正しい対処: public 以外のスキーマ(internal)へ移す。
--       PostgRESTが公開するのはExposed schemasだけなので、APIからは呼べなくなる。
--       RLSからは今までどおり呼べる（USAGEとEXECUTEを与える）。
